/** What a folded line is: a background task's report, a system reminder, a local command, session context, an interruption, a room line. */
export type FoldKind = 'task' | 'reminder' | 'command' | 'context' | 'interrupt' | 'system';

export interface FoldItem {
	readonly id: string;
	readonly kind: FoldKind;
	/** One line for the folded list. */
	readonly summary: string;
	/** A background task that finished (completed, failed or killed). */
	readonly done?: boolean;
}

const TAGS = 'system-reminder|task-notification|command-name|command-message|command-args|command-contents|local-command-stdout|local-command-stderr|local-command-caveat|bash-input|bash-stdout|bash-stderr|user-prompt-submit-hook|environment_context|user_instructions|turn_aborted|tool_use_error|artifact-view-context';
const BLOCK = new RegExp(`<(${TAGS})(?:\\s[^>]*)?>[\\s\\S]*?<\\/\\1>`, 'g');
const OPENING = new RegExp(`^<(${TAGS})(?:\\s[^>]*)?>`);
const PREFIXES: readonly [RegExp, FoldKind][] = [
	[/^Caveat: The messages below were generated by the user while running local commands/, 'command'],
	[/^\[Request interrupted by user/, 'interrupt'],
	[/^This session is being continued from a previous conversation/, 'context'],
	[/^# AGENTS\.md instructions/, 'context'],
];

const KIND_OF: Record<string, FoldKind> = {
	'task-notification': 'task', 'system-reminder': 'reminder', 'user-prompt-submit-hook': 'reminder',
	'environment_context': 'context', 'user_instructions': 'context', 'artifact-view-context': 'context', 'turn_aborted': 'interrupt', 'tool_use_error': 'command',
};

const oneLine = (text: string, n = 160) => {
	const line = text.replace(/\s+/g, ' ').trim();
	return line.length > n ? `${line.slice(0, n - 1)}…` : line;
};

const tag = (text: string, name: string) => new RegExp(`<${name}>([\\s\\S]*?)<\\/${name}>`).exec(text)?.[1]?.trim();

/**
 * A user-role entry that is not the user's words: a background task's report, a system reminder,
 * a local command's echo, injected session context (imported sessions carry these). Undefined: real text.
 */
export function backgroundNoise(text: string): Omit<FoldItem, 'id'> | undefined {
	const t = text.trim();
	if (!t) {
		return undefined;
	}
	for (const [re, kind] of PREFIXES) {
		if (re.test(t)) {
			return { kind, summary: oneLine(t.split('\n')[0]) };
		}
	}
	const first = OPENING.exec(t)?.[1];
	const rest = t.replace(BLOCK, '').trim();
	// A task report or a command echo is noise whatever trails it (Claude Code adds where its output is).
	const always = first === 'task-notification' || /^(command-|local-command-|bash-)/.test(first ?? '');
	if (rest && !always && !(first && rest === t)) {
		// Real words beside the blocks (a reminder glued to the user's text): not noise.
		return undefined;
	}
	if (!first) {
		return undefined;
	}
	const kind: FoldKind = KIND_OF[first] ?? 'command';
	if (first === 'task-notification') {
		const status = tag(t, 'status')?.toLowerCase();
		const summary = tag(t, 'summary') ?? tag(t, 'description') ?? (status ? `Background task ${status}` : 'Background task');
		return { kind, summary: oneLine(summary), ...(status && /^(completed|failed|killed|done|error|stopped)$/.test(status) ? { done: true } : {}) };
	}
	if (first === 'command-name' || first === 'command-message') {
		const name = tag(t, 'command-name') ?? tag(t, 'command-message') ?? '';
		const args = tag(t, 'command-args') ?? '';
		return { kind, summary: oneLine(`${name} ${args}`) };
	}
	const inner = t.replace(/<\/?[a-z_-]+(?:\s[^>]*)?>/gi, ' ');
	return { kind, summary: oneLine(inner) || first || kind };
}

/** The user's own words: system reminders and similar blocks glued to them are cut out. */
export function userWords(text: string): string {
	// What the user pasted, as the Claude app wraps it: the text stays, the wrapper goes.
	return text.replace(BLOCK, '').replace(/<\/?pasted_content(?:\s[^>]*)?>\n?/g, '').trim();
}

export type Row =
	| { readonly type: 'user'; readonly id: string; readonly at: string; readonly text: string; readonly attached: number }
	| { readonly type: 'agent'; readonly id: string; readonly at: string; readonly agentId: string; readonly name: string; readonly text: string }
	| { readonly type: 'fold'; readonly id: string; readonly items: readonly FoldItem[] }
	/**
	 * The error an agent's turn ended with, in plain words. `missing`: its CLI is not on that
	 * computer; `home`: the SSH agent whose machine has the thread's session (the view fills it in).
	 */
	| { readonly type: 'error'; readonly id: string; readonly agentId: string; readonly name: string; readonly text: string; readonly missing?: boolean; readonly home?: { readonly id: string; readonly machine: string } };

/** The room's messages as the panel's rows: consecutive system and background lines in one fold. */
export function threadRows(messages: readonly Message[]): Row[] {
	const rows: Row[] = [];
	const fold = (item: FoldItem) => {
		const last = rows.at(-1);
		if (last?.type === 'fold') {
			rows[rows.length - 1] = { ...last, items: [...last.items, item] };
		} else {
			rows.push({ type: 'fold', id: item.id, items: [item] });
		}
	};
	for (const m of messages) {
		if (m.author.kind === 'user') {
			const noise = backgroundNoise(m.text);
			if (noise) {
				fold({ id: m.id, ...noise });
				continue;
			}
			const { message, count } = withoutAttachments(m.text);
			const words = userWords(message);
			if (!words && !count) {
				continue;
			}
			rows.push({ type: 'user', id: m.id, at: m.at, text: words, attached: count });
		} else if (m.author.kind === 'agent') {
			// A turn that failed: what it wrote, then its error as an error row (`[error] …` in the room).
			const { answer, error } = splitError(m.text);
			if (answer || error === undefined) {
				rows.push({ type: 'agent', id: m.id, at: m.at, agentId: m.author.id, name: m.author.name, text: answer });
			}
			if (error !== undefined) {
				const readable = readableAgentError(error, m.author.id, machineOf(m.author.id) ? m.author.name.split(' · ')[1] || machineOf(m.author.id) : undefined);
				rows.push({ type: 'error', id: `${m.id}:error`, agentId: m.author.id, name: m.author.name, text: readable.text, ...(readable.missing ? { missing: true } : {}) });
			}
		} else {
			fold({ id: m.id, kind: 'system', summary: m.to ? oneLine(`${m.author.name}: ${instructionLine(m.text)}`) : oneLine(m.text) });
		}
	}
	return rows;
}

/** A fold's label: its one line, or what it holds counted. */
export function foldLabel(items: readonly FoldItem[], t: { tasksDone(n: number): string; tasks(n: number): string; other(n: number): string }): string {
	if (items.length === 1) {
		return items[0].summary;
	}
	const done = items.filter(i => i.kind === 'task' && i.done).length;
	const tasks = items.filter(i => i.kind === 'task' && !i.done).length;
	const other = items.length - done - tasks;
	return [done ? t.tasksDone(done) : '', tasks ? t.tasks(tasks) : '', other ? t.other(other) : ''].filter(Boolean).join(', ');
}

/** The leading slash command of a message typed in the panel, if it is one the room knows. */
export function parseSlash(text: string, known: readonly string[]): { command?: string; prompt: string } {
	const m = /^\/([a-z]+)(?:\s+([\s\S]*))?$/i.exec(text.trim());
	return m && known.includes(m[1].toLowerCase()) ? { command: m[1].toLowerCase(), prompt: (m[2] ?? '').trim() } : { prompt: text };
}

/** The machine part of an agent id: `claude@dev` → `dev`; a local agent has none. */
export function machineOf(agentId: string): string | undefined {
	const at = agentId.indexOf('@');
	return at >= 0 ? agentId.slice(at + 1) : undefined;
}

/** An answer's header: `Claude · tenark-claude`; a local agent's name gets the local label. */
export function agentLabel(name: string, agentId: string, local: string): string {
	return machineOf(agentId) || name.includes(' · ') ? name : `${name} · ${local}`;
}

/** The agent's own name without its machine: `Claude · dev` → `Claude`. */
export function agentTitle(name: string): string {
	return name.split(' · ')[0] || name;
}

/** The composer's agent chip: `Claude · tenark` for an SSH agent (its machine as named), `Claude` for a local one. */
export function agentChip(name: string, agentId: string): string {
	const machine = machineOf(agentId);
	return machine ? `${agentTitle(name)} · ${name.split(' · ')[1] ?? machine}` : agentTitle(name);
}

/** The provider an agent id belongs to, for its letter's colour. */
export function providerOf(agentId: string): 'claude' | 'codex' | 'other' {
	const base = agentId.split('@')[0].toLowerCase();
	return base.startsWith('claude') ? 'claude' : base.startsWith('codex') ? 'codex' : 'other';
}

/** One agent's turn while it runs: what it has written so far and its last tool line. */
export interface LivePart {
	readonly agentId: string;
	readonly text: string;
	readonly tool?: string;
	readonly error?: string;
	readonly since: string;
}

type LiveEvent = AgentEvent | { readonly kind: 'start' } | { readonly kind: 'end' };

/** The running turns per room, fed by the round's events; the panel streams them. */
export class LiveTurns {
	private readonly rooms = new Map<string, Map<string, LivePart>>();
	private readonly listeners = new Set<(roomId: string) => void>();

	onDidChange(listener: (roomId: string) => void): { dispose(): void } {
		this.listeners.add(listener);
		return { dispose: () => { this.listeners.delete(listener); } };
	}

	parts(roomId: string): LivePart[] {
		return [...this.rooms.get(roomId)?.values() ?? []];
	}

	feed(roomId: string, agentId: string, event: LiveEvent, now: () => string = () => new Date().toISOString()): void {
		let room = this.rooms.get(roomId);
		const part = room?.get(agentId);
		switch (event.kind) {
			case 'start':
				if (!room) {
					room = new Map();
					this.rooms.set(roomId, room);
				}
				room.set(agentId, { agentId, text: '', since: now() });
				break;
			case 'text':
				if (!part) {
					return;
				}
				room!.set(agentId, { ...part, text: part.text ? `${part.text}\n\n${event.text}` : event.text });
				break;
			case 'tool':
				if (!part) {
					return;
				}
				room!.set(agentId, { ...part, tool: event.text });
				break;
			case 'error':
				if (!part) {
					return;
				}
				room!.set(agentId, { ...part, error: event.text });
				break;
			case 'end':
				if (!part) {
					return;
				}
				room!.delete(agentId);
				if (!room!.size) {
					this.rooms.delete(roomId);
				}
				break;
			default:
				return;
		}
		for (const listener of [...this.listeners]) {
			listener(roomId);
		}
	}
}

/** `27m`, `2h 5m`, `40s`. */
export function elapsed(ms: number): string {
	const s = Math.max(0, Math.floor(ms / 1000));
	if (s < 60) {
		return `${s}s`;
	}
	const m = Math.floor(s / 60);
	if (m < 60) {
		return `${m}m`;
	}
	const h = Math.floor(m / 60);
	return m % 60 ? `${h}h ${m % 60}m` : `${h}h`;
}

export interface DetailsAgent {
	readonly id: string;
	readonly name: string;
	readonly turn: TurnState;
}

export interface DetailsTask {
	readonly name: string;
	readonly detail?: string;
	readonly kind: 'background' | 'subagent';
	readonly since: string;
	readonly elapsed: string;
}

export interface DetailsModel {
	readonly agents: readonly DetailsAgent[];
	/** Running background commands and sub-agents, longest-running first. */
	readonly running: readonly DetailsTask[];
	readonly finished: number;
	/** The fullest context of the thread's agents. */
	readonly context?: number;
}

/** The right panel's figures for a thread: its agents' states, their background work, the context fill. */
export function detailsModel(roster: readonly { id: string; name: string; activity: AgentActivity }[], now: number): DetailsModel {
	const running: DetailsTask[] = [];
	let finished = 0;
	let context: number | undefined;
	for (const a of roster) {
		const w = a.activity.work;
		for (const [kind, list] of [['background', w?.background ?? []], ['subagent', w?.subagents ?? []]] as const) {
			for (const item of list) {
				if (item.status === 'running') {
					running.push({ name: item.name, ...(item.detail ? { detail: item.detail } : {}), kind, since: item.since, elapsed: elapsed(now - Date.parse(item.since)) });
				} else {
					finished++;
				}
			}
		}
		const ctx = contextPercent(a.activity.usage);
		if (ctx !== undefined) {
			context = Math.max(context ?? 0, ctx);
		}
	}
	running.sort((a, b) => a.since.localeCompare(b.since));
	return {
		agents: roster.map(a => ({ id: a.id, name: a.name, turn: turnState(a.activity.state, a.activity.work, a.activity.error, !!a.activity.ran) })),
		running,
		finished,
		...(context !== undefined ? { context } : {}),
	};
}

/** A project or folder for the Environment section: a file URI's path, the home folder as `~`. */
export function folderLabel(folder: string | undefined, home: string | undefined): string | undefined {
	if (!folder) {
		return undefined;
	}
	let p = folder;
	if (/^file:\/\//.test(folder)) {
		try {
			p = decodeURIComponent(new URL(folder).pathname).replace(/^\/([A-Za-z]:)/, '$1');
		} catch {
			p = folder;
		}
	} else if (/^[a-z][\w+.-]*:\/\//i.test(folder)) {
		return folder;
	}
	return home && (p === home || p.startsWith(`${home}/`)) ? `~${p.slice(home.length)}` : p;
}

/**
 * The composer chip's labels (`Opus 5.5 · High`), read in the background. Cached per room, agent,
 * choice and the adopted session's model and context fill: a session read again (healed, moved to
 * its machine) shows its model without a reload. While a new label is read the last one for the
 * same choice stays (no flicker on every fill change); older labels of that agent are let go.
 */
export class LabelCache {
	private readonly labels = new Map<string, string | Promise<void>>();
	private readonly last = new Map<string, string>();

	/** The label, or undefined while there is none yet (the caller shows its plain one). */
	get(roomId: string, agentId: string, choice: object | undefined, adopted: { readonly model?: string; readonly context?: number } | undefined, read: () => Promise<string>, arrived: () => void): string | undefined {
		const base = `${roomId}:${agentId}:${JSON.stringify(choice ?? {})}`;
		const key = `${base}:${adopted?.model ?? ''}:${adopted?.context ?? ''}`;
		const known = this.labels.get(key);
		if (typeof known === 'string') {
			return known || undefined;
		}
		if (!known) {
			const done = (label: string) => {
				for (const k of this.labels.keys()) {
					if (k !== key && k.startsWith(`${roomId}:${agentId}:`) && typeof this.labels.get(k) === 'string') {
						this.labels.delete(k);
					}
				}
				this.labels.set(key, label);
				if (label) {
					this.last.set(base, label);
				}
			};
			this.labels.set(key, read().then(done, () => done('')).finally(arrived));
		}
		return this.last.get(base);
	}
}

/**
 * The composer's right side, as in the render: the model and effort chip (`Opus 5.5 · High`; `Models`
 * when several agents can choose), then the thread's permission mode (`Auto` or `Plan`). A
 * template room has its own plan step, so no mode chip there.
 */
export function composerRight(room: { readonly roster: readonly string[]; readonly state: Pick<RoomState, 'mode' | 'template'> }, canChoose: (agentId: string) => boolean, label: (agentId: string) => string, t: { readonly models: string; readonly auto: string; readonly plan: string; readonly modelTitle: string; readonly modeTitle: string }): object[] {
	const right: object[] = [];
	const choosers = room.roster.filter(canChoose);
	if (room.roster.length === 1 && choosers.length === 1) {
		right.push({ key: 'model', label: label(choosers[0]), cls: 'ghost', title: t.modelTitle, menu: { menu: 'model', agentId: choosers[0] } });
	} else if (choosers.length) {
		right.push({ key: 'model', label: t.models, cls: 'ghost', title: t.modelTitle, menu: { menu: 'models' } });
	}
	if (room.roster.length && !room.state.template) {
		right.push({ key: 'mode', label: room.state.mode === 'plan' ? t.plan : t.auto, cls: 'ghost', title: t.modeTitle, menu: { menu: 'mode' } });
	}
	return right;
}
