const TASK = `<task-notification>
<task-id>b8hi9mrnf</task-id>
<output-file>/tmp/tasks/b8hi9mrnf.output</output-file>
<status>completed</status>
<summary>Background command "Watch the dispatcher" completed (exit code 0)</summary>
</task-notification>
Read the output file to retrieve the result: /tmp/tasks/b8hi9mrnf.output`;

test('background reports, reminders and command echoes are not the user\'s words', () => {
	const task = backgroundNoise(TASK);
	assert.equal(task?.kind, 'task');
	assert.equal(task?.done, true);
	assert.equal(task?.summary, 'Background command "Watch the dispatcher" completed (exit code 0)');
	assert.equal(backgroundNoise('<task-notification><status>running</status></task-notification>')?.done, undefined);
	assert.equal(backgroundNoise('<system-reminder>\nThe task list is empty.\n</system-reminder>')?.kind, 'reminder');
	assert.deepEqual(backgroundNoise('<command-name>/clear</command-name>\n<command-message>clear</command-message>\n<command-args></command-args>'), { kind: 'command', summary: '/clear' });
	assert.equal(backgroundNoise('<local-command-stdout>done</local-command-stdout>')?.kind, 'command');
	assert.equal(backgroundNoise('Caveat: The messages below were generated by the user while running local commands. DO NOT respond.')?.kind, 'command');
	assert.equal(backgroundNoise('[Request interrupted by user for tool use]')?.kind, 'interrupt');
	assert.equal(backgroundNoise('This session is being continued from a previous conversation that ran out of context.')?.kind, 'context');
	assert.equal(backgroundNoise('<environment_context>\n  <cwd>/home/x</cwd>\n</environment_context>')?.kind, 'context');
	// A block cut off before its end is still not the user's words.
	assert.equal(backgroundNoise('<task-notification>\n<task-id>x</task-id>')?.kind, 'task');
});

test('real text stays the user\'s, a reminder glued to it is cut out', () => {
	assert.equal(backgroundNoise('tesztüzenet'), undefined);
	assert.equal(backgroundNoise('use <div> here please'), undefined);
	assert.equal(backgroundNoise(''), undefined);
	const glued = '<system-reminder>Today is Friday.</system-reminder>\nfix the stop state';
	assert.equal(backgroundNoise(glued), undefined);
	assert.equal(userWords(glued), 'fix the stop state');
	assert.equal(userWords('look at this\n<system-reminder>x</system-reminder>'), 'look at this');
});

const msg = (id: string, kind: 'user' | 'agent' | 'system', text: string, extra: Partial<Message> = {}): Message => ({
	id, at: '2026-11-14T10:00:00.000Z', author: kind === 'agent' ? { kind, id: 'claude@dev', name: 'Claude · dev' } : kind === 'user' ? { kind, id: 'user', name: 'You' } : { kind, id: 'room', name: 'Arkestra' }, text, ...extra,
});

test('rows: consecutive system and background lines fold into one, the rest keeps its order', () => {
	const rows = threadRows([
		msg('1', 'system', 'Claude session continued here (/home/x).'),
		msg('2', 'user', TASK),
		msg('3', 'agent', 'Restarted the watcher.'),
		msg('4', 'user', '<system-reminder>quiet</system-reminder>'),
		msg('5', 'user', 'tesztüzenet\n\n---\nHivatkozott anyagok (2):\n\n### a'),
		msg('6', 'system', 'Briefing\n---\nReview the slice plan.\nmore', { to: ['codex'] }),
		msg('7', 'user', '<system-reminder>x</system-reminder>\n'),
		msg('8', 'agent', 'Here.'),
	]);
	assert.deepEqual(rows.map(r => r.type), ['fold', 'agent', 'fold', 'user', 'fold', 'agent']);
	assert.equal(rows[0].type === 'fold' && rows[0].items.length, 2);
	assert.equal(rows[0].id, '1');
	const user = rows[3];
	assert.ok(user.type === 'user');
	assert.equal(user.text, 'tesztüzenet');
	assert.equal(user.attached, 2);
	const fold = rows[4];
	assert.ok(fold.type === 'fold');
	assert.deepEqual(fold.items.map(i => i.summary), ['Arkestra: Review the slice plan.', 'x']);
});

test('a fold is labelled by its one line, or by what it holds', () => {
	const t = { tasksDone: (n: number) => `${n} done`, tasks: (n: number) => `${n} tasks`, other: (n: number) => `${n} other` };
	assert.equal(foldLabel([{ id: 'a', kind: 'system', summary: 'Codex joined.' }], t), 'Codex joined.');
	assert.equal(foldLabel([
		{ id: 'a', kind: 'task', summary: '', done: true },
		{ id: 'b', kind: 'task', summary: '', done: true },
		{ id: 'c', kind: 'task', summary: '' },
		{ id: 'd', kind: 'reminder', summary: '' },
	], t), '2 done, 1 tasks, 1 other');
});

test('slash commands typed in the panel; unknown ones stay text', () => {
	const known = ['plan', 'invite', 'best'];
	assert.deepEqual(parseSlash('/plan add a login page', known), { command: 'plan', prompt: 'add a login page' });
	assert.deepEqual(parseSlash('/invite', known), { command: 'invite', prompt: '' });
	assert.deepEqual(parseSlash('/etc/hosts is broken', known), { prompt: '/etc/hosts is broken' });
	assert.deepEqual(parseSlash('/unknown x', known), { prompt: '/unknown x' });
	assert.deepEqual(parseSlash('hello /plan', known), { prompt: 'hello /plan' });
});

test('agent labels: the machine of an SSH agent, the local label for this machine', () => {
	assert.equal(machineOf('claude@tenark-claude'), 'tenark-claude');
	assert.equal(machineOf('claude'), undefined);
	assert.equal(agentLabel('Claude · tenark-claude', 'claude@tenark-claude', 'this machine'), 'Claude · tenark-claude');
	assert.equal(agentLabel('Claude', 'claude', 'this machine'), 'Claude · this machine');
	assert.equal(agentTitle('Codex · dev'), 'Codex');
	assert.equal(providerOf('codex@dev'), 'codex');
	assert.equal(providerOf('claude'), 'claude');
	assert.equal(providerOf('acp-gemini'), 'other');
});

test('live turns: text arrives in order per agent, the part goes when the turn ends', () => {
	const live = new LiveTurns();
	const fired: string[] = [];
	live.onDidChange(room => fired.push(room));
	const now = () => '2026-11-14T10:00:00.000Z';
	live.feed('r', 'a', { kind: 'text', text: 'before start' }, now);
	assert.deepEqual(live.parts('r'), []);
	live.feed('r', 'a', { kind: 'start' }, now);
	live.feed('r', 'a', { kind: 'text', text: 'one' }, now);
	live.feed('r', 'a', { kind: 'tool', text: 'Bash: npm test' }, now);
	live.feed('r', 'a', { kind: 'text', text: 'two' }, now);
	live.feed('r', 'a', { kind: 'usage', usage: { input: 1 } }, now);
	assert.deepEqual(live.parts('r'), [{ agentId: 'a', text: 'one\n\ntwo', tool: 'Bash: npm test', since: now() }]);
	live.feed('r', 'b', { kind: 'start' }, now);
	assert.deepEqual(live.parts('r').map(p => p.agentId), ['a', 'b']);
	live.feed('r', 'a', { kind: 'end' }, now);
	live.feed('r', 'b', { kind: 'error', text: 'quota' }, now);
	assert.deepEqual(live.parts('r'), [{ agentId: 'b', text: '', error: 'quota', since: now() }]);
	live.feed('r', 'b', { kind: 'end' }, now);
	assert.deepEqual(live.parts('r'), []);
	assert.equal(fired.length, 8);
});

test('right panel: running tasks longest first with elapsed time, finished count, fullest context', () => {
	assert.equal(elapsed(40_000), '40s');
	assert.equal(elapsed(27 * 60_000 + 5000), '27m');
	assert.equal(elapsed(125 * 60_000), '2h 5m');
	assert.equal(elapsed(-5), '0s');
	const now = Date.parse('2026-11-14T10:30:00.000Z');
	const a: AgentActivity = {
		state: 'answering', since: '', ran: true,
		usage: { input: 0, output: 0, cached: 0, context: { used: 62_000, window: 100_000 } },
		work: {
			...EMPTY_WORK,
			background: [
				{ id: '1', name: 'watch halts', status: 'running', since: '2026-11-14T10:03:00.000Z' },
				{ id: '2', name: 'old', status: 'done', since: '2026-11-14T09:00:00.000Z' },
			],
			subagents: [{ id: '3', name: 'reviewer', detail: 'T88', status: 'running', since: '2026-11-14T10:28:00.000Z' }],
		},
	};
	const b: AgentActivity = { state: 'idle', since: '', usage: { input: 0, output: 0, cached: 0, context: { used: 10, window: 100 } } };
	const m = detailsModel([{ id: 'a', name: 'Claude', activity: a }, { id: 'b', name: 'Codex', activity: b }], now);
	assert.deepEqual(m.running.map(t => [t.name, t.elapsed, t.kind]), [['watch halts', '27m', 'background'], ['reviewer', '2m', 'subagent']]);
	assert.equal(m.finished, 1);
	assert.equal(m.context, 62);
	assert.deepEqual(m.agents.map(x => x.turn), ['working', 'idle']);
	assert.equal(detailsModel([], now).context, undefined);
});

test('folders: a file URI as a path, the home folder as ~', () => {
	assert.equal(folderLabel('file:///home/r/tenark-dev', '/home/r'), '~/tenark-dev');
	assert.equal(folderLabel('/home/r', '/home/r'), '~');
	assert.equal(folderLabel('/srv/app', '/home/r'), '/srv/app');
	assert.equal(folderLabel('vscode-remote://ssh/x', '/home/r'), 'vscode-remote://ssh/x');
	assert.equal(folderLabel(undefined, '/home/r'), undefined);
});

test('markdown is escaped first: no raw HTML, no script links', () => {
	const html = renderMarkdown('<script>alert(1)</script> **bold** [x](javascript:alert(1)) [ok](https://a.b/c?d=1&e=2)');
	assert.ok(!html.includes('<script>'));
	assert.ok(html.includes('&lt;script&gt;'));
	assert.ok(html.includes('<strong>bold</strong>'));
	assert.ok(!html.includes('href="javascript'));
	assert.ok(html.includes('<a href="https://a.b/c?d=1&amp;e=2">ok</a>'));
	assert.ok(renderMarkdown('see https://x.y/z.').includes('<a href="https://x.y/z">https://x.y/z</a>.'));
	assert.ok(renderMarkdown('<img src=x onerror=alert(1)>').startsWith('<p>&lt;img'));
});

test('markdown: code blocks, inline code, headings, lists, tables, quotes', () => {
	assert.equal(renderMarkdown('```ts\nconst a = <T>(x: T) => x; // **no**\n```'), '<pre data-lang="ts"><code>const a = &lt;T&gt;(x: T) =&gt; x; // **no**</code></pre>');
	assert.equal(renderMarkdown('run `a **b**` now'), '<p>run <code>a **b**</code> now</p>');
	assert.equal(renderMarkdown('## Plan'), '<h4>Plan</h4>');
	assert.equal(renderMarkdown('- one\n- two\n  - nested\n- three'), '<ul><li>one</li><li>two<ul><li>nested</li></ul></li><li>three</li></ul>');
	assert.equal(renderMarkdown('3. c\n4. d'), '<ol start="3"><li>c</li><li>d</li></ol>');
	assert.equal(renderMarkdown('- [x] done\n- [ ] open'), '<ul><li><span class="task">☑</span> done</li><li><span class="task">☐</span> open</li></ul>');
	assert.equal(renderMarkdown('| a | b |\n|---|--:|\n| 1 | `x` |\n| 2 |'), '<div class="tbl"><table><thead><tr><th>a</th><th class="al-right">b</th></tr></thead><tbody><tr><td>1</td><td class="al-right"><code>x</code></td></tr><tr><td>2</td><td class="al-right"></td></tr></tbody></table></div>');
	assert.equal(renderMarkdown('> quoted\n> more'), '<blockquote><p>quoted<br>more</p></blockquote>');
	assert.equal(renderMarkdown('a\nb\n\nc'), '<p>a<br>b</p><p>c</p>');
	assert.equal(renderMarkdown('---'), '<hr>');
});

const S: ThreadStrings = { local: 'this machine', attached: n => `+${n} attached`, tasksDone: n => `${n} finished`, tasks: n => `${n} tasks`, other: n => `${n} other`, working: 'working…', copy: 'Copy' };

test('rows as HTML: the user bubble escaped, the answer with its agent and machine, the fold closed', () => {
	assert.equal(rowHtml({ type: 'user', id: '1', at: '', text: '<b>hi</b>\nthere', attached: 0 }, S), '<div class="ub">&lt;b&gt;hi&lt;/b&gt;<br>there</div>');
	const agent = rowHtml({ type: 'agent', id: '2', at: '', agentId: 'claude@tenark-claude', name: 'Claude · tenark-claude', text: 'Itt vagyok.' }, S, renderMarkdown, '23:21');
	assert.ok(agent.includes('<i class="av claude">C</i>Claude · tenark-claude'));
	assert.ok(agent.includes('<p>Itt vagyok.</p>'));
	assert.ok(agent.includes('<span>23:21</span>'));
	const fold = rowHtml({ type: 'fold', id: '3', items: [{ id: '3', kind: 'task', summary: 'a <b>', done: true }, { id: '4', kind: 'task', summary: 'b', done: true }] }, S);
	assert.ok(fold.startsWith('<details class="fold"><summary>2 finished'));
	assert.ok(fold.includes('a &lt;b&gt;'));
	const live = liveHtml({ agentId: 'codex', text: '', tool: 'Bash: ls', since: '' }, 'Codex', S);
	assert.ok(live.includes('Codex · this machine'));
	assert.ok(live.includes('<span class="pulse"></span>Bash: ls'));
	assert.equal(escapeHtml('"\'&'), '&quot;&#39;&amp;');
});
