const TASK = `<task-notification>
<task-id>b8hi9mrnf</task-id>
<output-file>/tmp/tasks/b8hi9mrnf.output</output-file>
<status>completed</status>
<summary>Background command "Watch the dispatcher" completed (exit code 0)</summary>
</task-notification>
Read the output file to retrieve the result: /tmp/tasks/b8hi9mrnf.output`;

test('background reports, reminders and command echoes are not the user\'s words', () => {
	const task = backgroundNoise(TASK);
	assert.equal(task?.kind, 'task');
	assert.equal(task?.done, true);
	assert.equal(task?.summary, 'Background command "Watch the dispatcher" completed (exit code 0)');
	assert.equal(backgroundNoise('<task-notification><status>running</status></task-notification>')?.done, undefined);
	assert.equal(backgroundNoise('<system-reminder>\nThe task list is empty.\n</system-reminder>')?.kind, 'reminder');
	assert.deepEqual(backgroundNoise('<command-name>/clear</command-name>\n<command-message>clear</command-message>\n<command-args></command-args>'), { kind: 'command', summary: '/clear' });
	assert.equal(backgroundNoise('<local-command-stdout>done</local-command-stdout>')?.kind, 'command');
	assert.equal(backgroundNoise('Caveat: The messages below were generated by the user while running local commands. DO NOT respond.')?.kind, 'command');
	assert.equal(backgroundNoise('[Request interrupted by user for tool use]')?.kind, 'interrupt');
	assert.equal(backgroundNoise('This session is being continued from a previous conversation that ran out of context.')?.kind, 'context');
	assert.equal(backgroundNoise('<environment_context>\n  <cwd>/home/x</cwd>\n</environment_context>')?.kind, 'context');
	// A block cut off before its end is still not the user's words.
	assert.equal(backgroundNoise('<task-notification>\n<task-id>x</task-id>')?.kind, 'task');
});

test('real text stays the user\'s, a reminder glued to it is cut out', () => {
	assert.equal(backgroundNoise('tesztüzenet'), undefined);
	assert.equal(backgroundNoise('use <div> here please'), undefined);
	assert.equal(backgroundNoise(''), undefined);
	const glued = '<system-reminder>Today is Friday.</system-reminder>\nfix the stop state';
	assert.equal(backgroundNoise(glued), undefined);
	assert.equal(userWords(glued), 'fix the stop state');
	assert.equal(userWords('look at this\n<system-reminder>x</system-reminder>'), 'look at this');
});

const msg = (id: string, kind: 'user' | 'agent' | 'system', text: string, extra: Partial<Message> = {}): Message => ({
	id, at: '2026-11-14T10:00:00.000Z', author: kind === 'agent' ? { kind, id: 'claude@dev', name: 'Claude · dev' } : kind === 'user' ? { kind, id: 'user', name: 'You' } : { kind, id: 'room', name: 'Arkestra' }, text, ...extra,
});

test('rows: consecutive system and background lines fold into one, the rest keeps its order', () => {
	const rows = threadRows([
		msg('1', 'system', 'Claude session continued here (/home/x).'),
		msg('2', 'user', TASK),
		msg('3', 'agent', 'Restarted the watcher.'),
		msg('4', 'user', '<system-reminder>quiet</system-reminder>'),
		msg('5', 'user', 'tesztüzenet\n\n---\nHivatkozott anyagok (2):\n\n### a'),
		msg('6', 'system', 'Briefing\n---\nReview the slice plan.\nmore', { to: ['codex'] }),
		msg('7', 'user', '<system-reminder>x</system-reminder>\n'),
		msg('8', 'agent', 'Here.'),
	]);
	assert.deepEqual(rows.map(r => r.type), ['fold', 'agent', 'fold', 'user', 'fold', 'agent']);
	assert.equal(rows[0].type === 'fold' && rows[0].items.length, 2);
	assert.equal(rows[0].id, '1');
	const user = rows[3];
	assert.ok(user.type === 'user');
	assert.equal(user.text, 'tesztüzenet');
	assert.equal(user.attached, 2);
	const fold = rows[4];
	assert.ok(fold.type === 'fold');
	assert.deepEqual(fold.items.map(i => i.summary), ['Arkestra: Review the slice plan.', 'x']);
});

