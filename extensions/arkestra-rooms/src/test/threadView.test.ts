test('live turns: text arrives in order per agent, the part goes when the turn ends', () => {
	const live = new LiveTurns();
	const fired: string[] = [];
	live.onDidChange(room => fired.push(room));
	const now = () => '2026-11-14T10:00:00.000Z';
	live.feed('r', 'a', { kind: 'text', text: 'before start' }, now);
	assert.deepEqual(live.parts('r'), []);
	live.feed('r', 'a', { kind: 'start' }, now);
	live.feed('r', 'a', { kind: 'text', text: 'one' }, now);
	live.feed('r', 'a', { kind: 'tool', text: 'Bash: npm test' }, now);
	live.feed('r', 'a', { kind: 'text', text: 'two' }, now);
	live.feed('r', 'a', { kind: 'usage', usage: { input: 1 } }, now);
	assert.deepEqual(live.parts('r'), [{ agentId: 'a', text: 'one\n\ntwo', tool: 'Bash: npm test', since: now() }]);
	live.feed('r', 'b', { kind: 'start' }, now);
	assert.deepEqual(live.parts('r').map(p => p.agentId), ['a', 'b']);
	live.feed('r', 'a', { kind: 'end' }, now);
	live.feed('r', 'b', { kind: 'error', text: 'quota' }, now);
	assert.deepEqual(live.parts('r'), [{ agentId: 'b', text: '', error: 'quota', since: now() }]);
	live.feed('r', 'b', { kind: 'end' }, now);
	assert.deepEqual(live.parts('r'), []);
	assert.equal(fired.length, 8);
});

test('right panel: running tasks longest first with elapsed time, finished count, fullest context', () => {
	assert.equal(elapsed(40_000), '40s');
	assert.equal(elapsed(27 * 60_000 + 5000), '27m');
	assert.equal(elapsed(125 * 60_000), '2h 5m');
	assert.equal(elapsed(-5), '0s');
	const now = Date.parse('2026-11-14T10:30:00.000Z');
	const a: AgentActivity = {
		state: 'answering', since: '', ran: true,
		usage: { input: 0, output: 0, cached: 0, context: { used: 62_000, window: 100_000 } },
		work: {
			...EMPTY_WORK,
			background: [
				{ id: '1', name: 'watch halts', status: 'running', since: '2026-11-14T10:03:00.000Z' },
				{ id: '2', name: 'old', status: 'done', since: '2026-11-14T09:00:00.000Z' },
			],
			subagents: [{ id: '3', name: 'reviewer', detail: 'T88', status: 'running', since: '2026-11-14T10:28:00.000Z' }],
		},
	};
	const b: AgentActivity = { state: 'idle', since: '', usage: { input: 0, output: 0, cached: 0, context: { used: 10, window: 100 } } };
	const m = detailsModel([{ id: 'a', name: 'Claude', activity: a }, { id: 'b', name: 'Codex', activity: b }], now);
	assert.deepEqual(m.running.map(t => [t.name, t.elapsed, t.kind]), [['watch halts', '27m', 'background'], ['reviewer', '2m', 'subagent']]);
	assert.equal(m.finished, 1);
	assert.equal(m.context, 62);
	assert.deepEqual(m.agents.map(x => x.turn), ['working', 'idle']);
	assert.equal(detailsModel([], now).context, undefined);
});

